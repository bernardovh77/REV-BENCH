#!/usr/bin/env python3
"""Generates the app's snapshot-v2 decoder from the contract's layout (stage 124).

    python tools/gen_snapshot_ts.py            writes the two files below
    python tools/gen_snapshot_ts.py --check    exits 1 if either is not what it would write

  app/src/shared/snapshot-v2.generated.ts   the decoder (and an encoder, for the fake add-on
                                            and the tests), every offset taken from
                                            tools/snapshot_v2.py's tables, which stage 121
                                            checks against the C core
  app/tests/golden/snapshot-v2-i4-idle.json what tools/snapshot_v2.py reads from
                                            contracts/examples/snapshot-v2-i4-idle.bin: the
                                            decoder's test must read the same values

Nothing in the app copies an offset by hand: change the layout in snapshot_v2.py (and the C), run
this, and the decoder follows; python's test_gen_snapshot_ts.py fails while the committed files
are stale.
"""
import json
from pathlib import Path
import sys

import snapshot_v2 as layout

ROOT = Path(__file__).resolve().parents[1]
TS_FILE = ROOT / "app/src/shared/snapshot-v2.generated.ts"
GOLDEN_FILE = ROOT / "app/tests/golden/snapshot-v2-i4-idle.json"
EXAMPLE = ROOT / "contracts/examples/snapshot-v2-i4-idle.bin"
# 64-bit fields that are hashes, not counters: they stay exact as bigint (the rest are
# counters that stay below 2^53 for centuries, and are numbers)
BIGINT_FIELDS = {"build_id"}
TS_TYPE = {"u32": "number", "u64": "number", "f64": "number"}
READ = {"u32": "getUint32", "u64": "getBigUint64", "f64": "getFloat64"}


def ts_type(kind, name):
    return "bigint" if name in BIGINT_FIELDS else TS_TYPE[kind]


def read_expr(offset, name, kind):
    if kind == "u64" and name not in BIGINT_FIELDS:
        return f"counter(view, {offset}, {json.dumps(name)})"
    return f"view.{READ[kind]}({offset}, true)"


def write_stmt(offset, name, kind):
    if kind == "u32":
        return f"view.setUint32({offset}, h.{name}, true);"
    if kind == "u64":
        value = f"h.{name}" if name in BIGINT_FIELDS else f"BigInt(h.{name})"
        return f"view.setBigUint64({offset}, {value}, true);"
    return f"view.setFloat64({offset}, h.{name}, true);"


def render_ts():
    header = layout.HEADER
    n_instruments = len(layout.INSTRUMENTS)
    n_fields = len(layout.CYLINDER_FIELDS)
    lines = []
    out = lines.append
    out("/*")
    out(" * GENERATED by tools/gen_snapshot_ts.py from tools/snapshot_v2.py (contracts/snapshot-v2.md).")
    out(" * Do not edit: change the layout there, run the generator, commit both. Python's")
    out(" * test_gen_snapshot_ts.py fails while this file is stale, and the decoder's Vitest test")
    out(" * reads contracts/examples/snapshot-v2-i4-idle.bin to the values snapshot_v2.py reads.")
    out(" *")
    out(" * The names are the contract's own (snake_case), not renamed.")
    out(" */")
    out("")
    out(f"export const SNAPSHOT_MAGIC = {layout.MAGIC:#x};")
    out(f"export const SNAPSHOT_VERSION = {layout.VERSION};")
    out(f"export const HEADER_SIZE = {layout.HEADER_SIZE};")
    out(f"export const INSTRUMENTS_OFFSET = {layout.HEADER_SIZE};")
    out(f"export const CYLINDERS_OFFSET = {layout.HEADER_SIZE + 8 * n_instruments};")
    out(f"export const CYLINDER_STRIDE = {8 * n_fields};")
    out("export const MAX_CYLINDERS = 16;")
    out("")
    out("export const INSTRUMENT_NAMES = [")
    for name in layout.INSTRUMENTS:
        out(f'  "{name}",')
    out("] as const;")
    out("export type InstrumentName = (typeof INSTRUMENT_NAMES)[number];")
    out("")
    out("export const CYLINDER_FIELD_NAMES = [")
    for name in layout.CYLINDER_FIELDS:
        out(f'  "{name}",')
    out("] as const;")
    out("export type CylinderFieldName = (typeof CYLINDER_FIELD_NAMES)[number];")
    out("")
    out("/** The bytes of a snapshot of n cylinders. */")
    out("export function snapshotSize(cylinders: number): number {")
    out("  return CYLINDERS_OFFSET + CYLINDER_STRIDE * cylinders;")
    out("}")
    out("")
    out("export interface SnapshotHeader {")
    for _, name, kind in header:
        out(f"  {name}: {ts_type(kind, name)};")
    out("}")
    out("")
    out("export type CylinderState = Record<CylinderFieldName, number>;")
    out("")
    out("/**")
    out(" * One snapshot, decoded: the header's fields, then the instruments by name (in place of the")
    out(" * header's count of them, as snapshot_v2.py's `parse` has it) and the cylinders.")
    out(" */")
    out('export interface Snapshot extends Omit<SnapshotHeader, "instruments"> {')
    out("  instruments: Record<InstrumentName, number>;")
    out("  cylinder: CylinderState[];")
    out("}")
    out("")
    out("/** A snapshot the contract's rules refuse. */")
    out("export class SnapshotError extends Error {")
    out("  constructor(message: string) {")
    out("    super(message);")
    out('    this.name = "SnapshotError";')
    out("  }")
    out("}")
    out("")
    out("function fail(why: string): never {")
    out("  throw new SnapshotError(why);")
    out("}")
    out("")
    out("/** A 64-bit counter as a number; one past 2^53 is refused, not rounded. */")
    out("function counter(view: DataView, offset: number, name: string): number {")
    out("  const v = view.getBigUint64(offset, true);")
    out("  if (v > BigInt(Number.MAX_SAFE_INTEGER)) fail(`${name} does not fit in a number`);")
    out("  return Number(v);")
    out("}")
    out("")
    out("/** Reads one snapshot, checked on its own by the contract's rules (snapshot_v2.py's `parse`). */")
    out("export function decodeSnapshot(bytes: ArrayBuffer | ArrayBufferView): Snapshot {")
    out("  // isView, not instanceof: bytes that crossed a MessagePort may come from another realm")
    out("  const view = ArrayBuffer.isView(bytes)")
    out("    ? new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength)")
    out("    : new DataView(bytes);")
    out("  if (view.byteLength < HEADER_SIZE) fail(\"shorter than the header\");")
    out("  const h: SnapshotHeader = {")
    for offset, name, kind in header:
        out(f"    {name}: {read_expr(offset, name, kind)},")
    out("  };")
    out("  if (h.magic !== SNAPSHOT_MAGIC) fail(`magic ${h.magic.toString(16)}, not RBS2`);")
    out("  if (h.version !== SNAPSHOT_VERSION) fail(`version ${h.version}, not ${SNAPSHOT_VERSION}`);")
    out("  if (h.instruments !== INSTRUMENT_NAMES.length || h.cylinder_fields !== CYLINDER_FIELD_NAMES.length) {")
    out("    fail(\"instruments or cylinder fields aren't this version's\");")
    out("  }")
    out("  if (h.cylinders < 1 || h.cylinders > MAX_CYLINDERS) fail(`${h.cylinders} cylinders`);")
    out("  if (h.reserved0 !== 0 || h.reserved1 !== 0) fail(\"reserved words not 0\");")
    out("  const need = snapshotSize(h.cylinders);")
    out("  if (h.size !== need || view.byteLength !== need) fail(`size ${h.size}, the layout needs ${need}`);")
    out("  for (const name of [\"physics_hz\", \"audio_hz\"] as const) {")
    out("    if (!(Number.isFinite(h[name]) && h[name] > 0)) fail(`${name} ${h[name]}`);")
    out("  }")
    out("  if (!(h.phase_rad >= 0 && h.phase_rad < 4 * Math.PI)) fail(`phase ${h.phase_rad} outside [0, 4 pi)`);")
    out("  if (!(Number.isFinite(h.speed_rad_s) && h.speed_rad_s >= 0)) fail(`speed ${h.speed_rad_s}`);")
    out("  const instruments = {} as Record<InstrumentName, number>;")
    out("  INSTRUMENT_NAMES.forEach((name, i) => {")
    out("    const v = view.getFloat64(INSTRUMENTS_OFFSET + 8 * i, true);")
    out("    if (!Number.isFinite(v)) fail(\"an instrument isn't a number\");")
    out("    instruments[name] = v;")
    out("  });")
    out("  const cylinder: CylinderState[] = [];")
    out("  for (let c = 0; c < h.cylinders; c++) {")
    out("    const row = {} as CylinderState;")
    out("    CYLINDER_FIELD_NAMES.forEach((name, f) => {")
    out("      row[name] = view.getFloat64(CYLINDERS_OFFSET + CYLINDER_STRIDE * c + 8 * f, true);")
    out("    });")
    out("    if (!(row.pressure > 0 && row.temperature > 0)) fail(`cylinder ${c}: pressure and temperature must be positive`);")
    out("    if (!(row.burn >= 0 && row.burn <= 1)) fail(`cylinder ${c}: burn fraction ${row.burn}`);")
    out("    if (!(row.intake_lift >= 0 && row.exhaust_lift >= 0)) fail(`cylinder ${c}: a negative valve lift`);")
    out("    cylinder.push(row);")
    out("  }")
    out("  return { ...h, instruments, cylinder };")
    out("}")
    out("")
    out("/**")
    out(" * Writes a snapshot in the layout (the fake add-on's and the tests' side). The header's")
    out(" * `size`, `magic`, `version` and counts are the layout's, whatever `s` says.")
    out(" */")
    out("export function encodeSnapshot(s: Snapshot): ArrayBuffer {")
    out("  const n = s.cylinder.length;")
    out("  const buffer = new ArrayBuffer(snapshotSize(n));")
    out("  const view = new DataView(buffer);")
    out("  const h: SnapshotHeader = {")
    out("    ...s,")
    out("    magic: SNAPSHOT_MAGIC,")
    out("    version: SNAPSHOT_VERSION,")
    out("    size: buffer.byteLength,")
    out("    cylinders: n,")
    out("    instruments: INSTRUMENT_NAMES.length,")
    out("    cylinder_fields: CYLINDER_FIELD_NAMES.length,")
    out("    reserved0: 0,")
    out("    reserved1: 0,")
    out("  };")
    for offset, name, kind in header:
        out(f"  {write_stmt(offset, name, kind)}")
    out("  INSTRUMENT_NAMES.forEach((name, i) => view.setFloat64(INSTRUMENTS_OFFSET + 8 * i, s.instruments[name], true));")
    out("  s.cylinder.forEach((row, c) => {")
    out("    CYLINDER_FIELD_NAMES.forEach((name, f) => {")
    out("      view.setFloat64(CYLINDERS_OFFSET + CYLINDER_STRIDE * c + 8 * f, row[name], true);")
    out("    });")
    out("  });")
    out("  return buffer;")
    out("}")
    return "\n".join(lines) + "\n"


def golden_object(snap):
    """A parsed snapshot as JSON: the 64-bit hash as a decimal string, as a bigint is in the app."""
    out = dict(snap)
    out["build_id"] = str(snap["build_id"])
    return out


def render_golden():
    snaps = layout.check_stream(EXAMPLE.read_bytes())
    return json.dumps([golden_object(s) for s in snaps], indent=1) + "\n"


def outputs():
    return {TS_FILE: render_ts(), GOLDEN_FILE: render_golden()}


def main():
    check = sys.argv[1:] == ["--check"]
    if sys.argv[1:] and not check:
        sys.exit(__doc__)
    stale = []
    for path, text in outputs().items():
        if check:
            if not path.is_file() or path.read_text(encoding="utf-8") != text:
                stale.append(path.relative_to(ROOT).as_posix())
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
            print(f"wrote {path.relative_to(ROOT).as_posix()}")
    if stale:
        sys.exit("gen_snapshot_ts: stale, run python tools/gen_snapshot_ts.py: " + ", ".join(stale))


if __name__ == "__main__":
    main()
